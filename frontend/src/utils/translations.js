// Helper function to get translation
export const t = (key, language = 'en', params = {}) => {
  let translation = translations[language]?.[key] || translations['en'][key] || key;
  
  // Replace parameters in the translation string
  Object.keys(params).forEach(param => {
    translation = translation.replace(`{{${param}}}`, params[param]);
  });
  
  return translation;
};

// Get user's preferred language
export const getUserLanguage = () => {
  return localStorage.getItem('preferredLanguage') || 'en';
};

// Set user's preferred language
export const setUserLanguage = (language) => {
  if (translations[language]) {
    localStorage.setItem('preferredLanguage', language);
    return true;
  }
  return false;
};

// Get available languages
export const getAvailableLanguages = () => {
  return Object.keys(translations).map(code => ({
    code,
    name: getLanguageName(code)
  }));
};

// Get language name in native form
export const getLanguageName = (code) => {
  const names = {
    en: 'English',
    es: 'Español',
    hi: 'हिन्दी'
  };
  return names[code] || code;
};

// Format number with localization
export const formatNumber = (number, language = 'en') => {
  return new Intl.NumberFormat(language).format(number);
};

// Format currency
export const formatCurrency = (amount, language = 'en', currency = 'USD') => {
  return new Intl.NumberFormat(language, { style: 'currency', currency }).format(amount);
};

// Format date
export const formatDate = (date, language = 'en') => {
  return new Intl.DateTimeFormat(language).format(new Date(date));
};

// Get direction for RTL languages
export const getTextDirection = (language) => {
  const rtlLanguages = ['ar', 'he', 'ur'];
  return rtlLanguages.includes(language) ? 'rtl' : 'ltr';
};